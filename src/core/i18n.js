function normalizeAppLanguage(value = '') {
  const raw = String(value || '').trim().toLowerCase().replace('_', '-');
  if (raw === 'es' || raw.startsWith('es-') || raw === 'spanish' || raw === 'espanol' || raw === 'español') return 'es';
  return 'en';
}

function interpolate(template, values = {}) {
  return String(template || '').replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match);
}

function translate(language, key, values = {}, fallback = '') {
  const lang = normalizeAppLanguage(language);
  const row = STRINGS[lang] || STRINGS.en;
  const template = row[key] ?? STRINGS.en[key] ?? fallback ?? key;
  return interpolate(template, values);
}

function localeForLanguage(language) {
  return normalizeAppLanguage(language) === 'es' ? 'es-US' : 'en-US';
}

function dateFromIso(value = '') {
  const clean = String(value || '').slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(clean)) return null;
  const date = new Date(`${clean}T12:00:00`);
  return Number.isFinite(date.getTime()) ? date : null;
}

function formatLocalizedDate(value, language, options = {}) {
  const date = dateFromIso(value) || (value instanceof Date ? value : null);
  if (!date || !Number.isFinite(date.getTime())) return String(value || '');
  return new Intl.DateTimeFormat(localeForLanguage(language), { month: 'short', day: 'numeric', year: 'numeric', ...options }).format(date);
}

function formatLocalizedFullDate(value, language) {
  const date = dateFromIso(value) || (value instanceof Date ? value : null);
  if (!date || !Number.isFinite(date.getTime())) return String(value || '');
  return new Intl.DateTimeFormat(localeForLanguage(language), { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric' }).format(date);
}

function formatLocalizedMonth(value, language) {
  const clean = String(value || '').slice(0, 7);
  const date = /^\d{4}-\d{2}$/.test(clean) ? new Date(`${clean}-01T12:00:00`) : null;
  if (!date || !Number.isFinite(date.getTime())) return String(value || '');
  return new Intl.DateTimeFormat(localeForLanguage(language), { month: 'long', year: 'numeric' }).format(date);
}

function getMissingTranslationKeys(language = 'es') {
  const lang = normalizeAppLanguage(language);
  return Object.keys(STRINGS.en).filter(key => !Object.prototype.hasOwnProperty.call(STRINGS[lang] || {}, key));
}

